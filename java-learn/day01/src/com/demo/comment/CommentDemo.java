package com.demo.comment;

/**
 * 3、文档注释
 * 一般用在类上，方法上，就是很专业的
 * 里面的内容可以提取到程序说明书中去
 */
public class CommentDemo {
    public static void main(String[] args) {
        // 1、单行注释，以下是输出一句诗，会打印出来，666
        System.out.println("轻舟已过万重山！");

        /*
         2、多行注释
         我准备创作一首诗
         会打印出来
         小白不要删除我的代码
         */
        System.out.println("莫道桑榆晚");
        System.out.println("为霞尚满天");
    }
}

